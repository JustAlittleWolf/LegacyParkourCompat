    public PaneNeighborEligibility() {
    }

    @Override
    public Result classify(BlockState neighborState) {
        String blockId = MovementRuntime.blockId(neighborState.getBlock());
        if (CUBE_PROVIDER_IDS.contains(blockId) || PANE_OR_GLASS_EXCEPTION_IDS.contains(blockId)) {
            return Result.ELIGIBLE;
        }
        if (AMBIGUOUS_SLAB_IDS.contains(blockId)) {
            if (!neighborState.hasProperty(SlabBlock.TYPE)) {
                return Result.NATIVE;
            }
            return neighborState.getValue(SlabBlock.TYPE) == SlabType.DOUBLE
                ? Result.ELIGIBLE
                : Result.INELIGIBLE;
        }
        if (FALSE_PROVIDER_IDS.contains(blockId)) {
            return Result.INELIGIBLE;
        }
        return Result.NATIVE;
    }
